def warranty_terms_html(*, paragraphs: bool = False) -> str:
    """Keep legacy inline markup while giving v6 the approved paragraph breaks."""
    items = []
    for title, texts in WARRANTY_TERMS:
        body = (
            "".join(f'<p class="doc-terms__paragraph">{escape(text)}</p>' for text in texts)
            if paragraphs
            else " " + escape(" ".join(texts))
        )
        items.append(f"  <li><strong>{escape(title)}</strong>{body}</li>")
    return (
        f'<p class="doc-terms__lead">{escape(WARRANTY_LEAD)}</p>\n'
        '<ol class="doc-terms__list">\n' + "\n".join(items) + "\n</ol>"
    )
